#!/usr/bin/env python3
"""trace-seeds.py IMAGE SET.jsonl... --source TEXT -- the ROM addresses MAME executed, as seeds.

Ghidra decodes as a 68040 and finds much of the code through heuristics that read data as
pointers, and those heuristics also type real code as data or start an instruction inside
another. An address the machine executed is an instruction start by definition, so the import
disassembles every one of them before the analysis runs (SetupTCH.java), and the export checks that
each still starts an instruction afterwards (verify-listings.py).

The input is a MAME debugger trace (its `trace` command) reduced to its distinct addresses, one JSON
object per line with "addr". Only ROM addresses are kept: code
the game copied to RAM runs at another address than its bytes. Several sets of one image merge.

Output: disasm/executed/IMAGE.txt, a `#` header naming the runs (`--source`, one per set, in the
same order) and one hex address per line, sorted. Exit 3 when the sets hold no ROM address.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from memory_map import ROM_END

ROOT = Path(__file__).resolve().parents[1]
OUTDIR = ROOT / "disasm" / "executed"


def rom_addresses(set_path: Path) -> set[int]:
    out = set()
    for line in set_path.read_text().splitlines():
        if line.strip():
            addr = int(json.loads(line)["addr"], 16)
            if addr < ROM_END:
                out.add(addr)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("image", help="the image the sets were traced on, e.g. radendur_maincpu")
    ap.add_argument("sets", type=Path, nargs="+", help="the tracer's .set.jsonl files")
    ap.add_argument("--source", action="append", required=True, help="what each run was")
    args = ap.parse_args()
    if len(args.source) != len(args.sets):
        ap.error("one --source per set")
    addrs: set[int] = set()
    for s in args.sets:
        addrs |= rom_addresses(s)
    if not addrs:
        print(f"INVALID: no ROM address in {', '.join(map(str, args.sets))}", file=sys.stderr)
        return 3
    OUTDIR.mkdir(parents=True, exist_ok=True)
    header = [
        f"# {args.image}: ROM addresses MAME executed, GENERATED by scripts/trace-seeds.py from:",
        *(f"#   {src}" for src in args.source),
        "# Every one is an instruction start; SetupTCH.java disassembles them before the analysis.",
    ]
    body = [f"0x{a:06x}" for a in sorted(addrs)]
    (OUTDIR / f"{args.image}.txt").write_text("\n".join(header + body) + "\n")
    print(f"trace-seeds: {args.image}: {len(addrs)} addresses")
    return 0


if __name__ == "__main__":
    sys.exit(main())
