"""verify-docs.py -- the documentation holds together: every relative link and image points at a
file that exists (with the exact case, as GitHub serves it), every generated block is closed and
filled, and every generator still produces what its blocks hold (`--check`).

Use:
    uv run scripts/verify-docs.py

Exit: 0 coherent | 1 a broken link or a stale block | 3 there was no document to check
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parents[1]
LINK = re.compile(r"\[[^\]]*\]\(<?([^)>\s]+?)>?(?:\s+\"[^\"]*\")?\)")
IMAGE = re.compile(r'<img[^>]+src="([^"]+)"')
ANCHOR = re.compile(r'<a[^>]+href="([^"]+)"')
# the markers doc_blocks.py writes into every generated document
GENERATED = re.compile(
    r"<!-- generated by (\S+): do not edit by hand(?: \[[^\]]+\])? -->\n"
    r"(.*?)<!-- end of generated block -->",
    re.S,
)


def documents() -> list[Path]:
    """Every Markdown file git tracks or would track, so a page written today is checked too."""
    out: list[str] = []
    for extra in ([], ["--others", "--exclude-standard"]):
        r = subprocess.run(
            ["git", "ls-files", "-z", *extra, "*.md"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        )
        out += r.stdout.split("\0")
    return sorted({ROOT / d for d in out if d and (ROOT / d).is_file()})


def targets(text: str) -> list[str]:
    """Link targets outside code, where a link is an example and not a link."""
    t = re.sub(r"`[^`\n]*`", " ", re.sub(r"```.*?```", " ", text, flags=re.S))
    return [m.group(1) for pat in (LINK, IMAGE, ANCHOR) for m in pat.finditer(t)]


def main() -> int:
    docs = documents()
    if not docs:
        print("INVALID: no Markdown to check")
        return 3
    failures: list[str] = []
    generators: set[str] = set()
    for md in docs:
        text = md.read_text()
        rel = md.relative_to(ROOT)
        for target in targets(text):
            if target.startswith(("http://", "https://", "mailto:", "#")):
                continue
            path = (md.parent / unquote(target.split("#")[0])).resolve()
            if not path.exists():
                failures.append(f"{rel}: broken link to `{target}`")
            elif path.name not in [q.name for q in path.parent.iterdir()]:
                failures.append(f"{rel}: `{target}` only matches ignoring case")
        for m in GENERATED.finditer(text):
            generators.add(m.group(1))
            if not (ROOT / m.group(1)).exists():
                failures.append(f"{rel}: the block names `{m.group(1)}`, which does not exist")
            elif not m.group(2).strip():
                failures.append(f"{rel}: the block of `{m.group(1)}` is empty")
        if text.count("<!-- generated by ") != text.count("<!-- end of generated block -->"):
            failures.append(f"{rel}: a generated block is not closed")
    for generator in sorted(generators):
        r = subprocess.run(
            ["uv", "run", generator, "--check"], cwd=ROOT, capture_output=True, text=True
        )
        if r.returncode != 0:
            failures.append(f"`{generator} --check` fails: {r.stdout.strip() or r.stderr.strip()}")
    print(f"documents checked: {len(docs)}   generators: {len(generators)}")
    for f in failures:
        print(f"  {f}")
    if failures:
        return 1
    print("==> links, images and generated blocks are coherent")
    return 0


if __name__ == "__main__":
    sys.exit(main())
