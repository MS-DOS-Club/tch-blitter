"""doc_blocks.py -- the generated blocks inside hand-written documents, shared by every generator.

A block opens with `<!-- generated by scripts/<generator>: do not edit by hand [<label>] -->` and
closes with `<!-- end of generated block -->`; verify-docs.py reads the same markers.
"""

from __future__ import annotations

import sys

END = "<!-- end of generated block -->"
OPENER = "<!-- generated by "


def opener(generator: str, label: str | None = None) -> str:
    tag = f" [{label}]" if label else ""
    return f"{OPENER}scripts/{generator}: do not edit by hand{tag} -->"


def replace(text: str, start: str, body: str, where: str) -> str:
    """`text` with the block that `start` opens holding `body`; exits 3 when the block is missing,
    duplicated or not closed, since writing then would lose prose or leave a stale copy."""
    if text.count(start) != 1:
        print(f"INVALID: {where} holds {text.count(start)} blocks opened by `{start}`, not one")
        sys.exit(3)
    i = text.index(start) + len(start)
    j = text.find(END, i)
    if j < 0 or OPENER in text[i:j]:
        print(f"INVALID: the block `{start}` of {where} has no close of its own")
        sys.exit(3)
    return text[:i] + "\n" + body + text[j:]
