#!/usr/bin/env python3
"""scan-hw-accesses.py -- which hardware each game touches, counted over the binary: how many times
it references each hardware address, with which instruction and from where. Only absolute 32-bit
references are counted, which is how these games program the blitter; an access through a pointer
does not appear, and the output says so.

Use:
    uv run scripts/scan-hw-accesses.py            updates hardware/accesses.yaml
    uv run scripts/scan-hw-accesses.py --check    fails if the file is not up to date
"""

import argparse
import pathlib
import struct
import sys

import yaml
from memory_map import BLITTER_LAST, BLITTER_START

ROOT = pathlib.Path(__file__).resolve().parent.parent
IMGS = ROOT / "disasm" / "img"
OUT_FILE = ROOT / "hardware" / "accesses.yaml"

# The board's hardware ranges, from the drivers' address_map. Outside these, a word that "looks
# like" an address is nearly always data.
RANGES = [
    (BLITTER_START, BLITTER_LAST, "blitter"),
    (0x720000, 0x720005, "ramdac"),
    (0x740000, 0x740001, "soundlatch / dac"),
    (0x760000, 0x760001, "coin counter"),
    (0x780000, 0x78000F, "adc / sub soundlatch"),
    (0x7A0000, 0x7A0001, "line counter"),
    (0x7C0000, 0x7C0001, "status and eeprom"),
    (0x7E0000, 0x7E0003, "inputs"),
]


def classify(addr):
    for lo, hi, name in RANGES:
        if lo <= addr <= hi:
            return name
    return None


def scan(path):
    d = path.read_bytes()
    accesses = {}
    for i in range(0, len(d) - 4, 2):
        v = struct.unpack(">I", d[i : i + 4])[0]
        zone = classify(v)
        if zone is None:
            continue
        e = accesses.setdefault(v, {"addr": v, "zone": zone, "refs": 0})
        e["refs"] += 1
    return sorted(accesses.values(), key=lambda e: e["addr"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    images = sorted(p for p in IMGS.glob("*.bin"))
    if not images:
        print("INVALID: no images in disasm/img; run make disasm")
        return 3

    data = {
        "_note": (
            "Generated by scripts/scan-hw-accesses.py. It counts only 32-bit ABSOLUTE "
            "references: anything reached through a pointer does not appear here."
        ),
        "images": {},
    }
    for img in images:
        accesses = scan(img)
        data["images"][img.stem] = {
            "total": sum(a["refs"] for a in accesses),
            "accesses": accesses,
        }

    text = yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=100)
    if args.check:
        if not OUT_FILE.exists() or OUT_FILE.read_text() != text:
            print(
                f"{OUT_FILE.relative_to(ROOT)} is out of date: run "
                "uv run scripts/scan-hw-accesses.py"
            )
            return 1
        print(f"accesses up to date ({len(images)} images)")
        return 0

    OUT_FILE.write_text(text)
    for name, info_ in data["images"].items():
        print(
            f"  {name:22s} {info_['total']:5d} hardware references, "
            f"{len(info_['accesses'])} distinct addresses"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
